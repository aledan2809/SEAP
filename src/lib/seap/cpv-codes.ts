export const ALL_IT_CPV_CODES = Object.keys(IT_CPV_CODES);

/**
 * Obține descrierea unui cod CPV
 */
export function getCpvDescription(code: string): string | undefined {
  return IT_CPV_CODES[code as CpvCode];
}

/**
 * Caută coduri CPV după text
 */
export function searchCpvCodes(query: string): Array<{ code: string; description: string }> {
  const lowerQuery = query.toLowerCase();
  return Object.entries(IT_CPV_CODES)
    .filter(([code, description]) =>
      code.includes(query) || description.toLowerCase().includes(lowerQuery)
    )
    .map(([code, description]) => ({ code, description }));
}
